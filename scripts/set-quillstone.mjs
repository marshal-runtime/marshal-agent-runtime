// Pins the runtime to a Quillstone release: node scripts/set-quillstone.mjs <tag> (then run quillstone:fetch and commit vendor/quillstone)
// Reads quillstone-release.json from the release, rewrites quillstone.lock.json and the pnpm overrides in pnpm-workspace.yaml.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tag = process.argv[2];
if (!/^v\d+\.\d+\.\d+/.test(tag ?? '')) {
  console.error('usage: node scripts/set-quillstone.mjs <tag, e.g. v0.1.0>');
  process.exit(2);
}
const repository = 'marshal-runtime/quillstone';
const env = { ...process.env, ...(process.env.QUILLSTONE_TOKEN ? { GH_TOKEN: process.env.QUILLSTONE_TOKEN } : {}) };
const manifest = JSON.parse(execFileSync('gh', ['release', 'download', tag, '--repo', repository, '--pattern', 'quillstone-release.json', '--output', '-'], { env, encoding: 'utf8', maxBuffer: 1 << 24 }));
writeFileSync(join(root, 'quillstone.lock.json'), `${JSON.stringify({ repository, tag, gitSha: manifest.gitSha, packages: manifest.packages }, null, 2)}\n`);

const workspaceFile = join(root, 'pnpm-workspace.yaml');
const begin = '  # quillstone:begin (generated by scripts/set-quillstone.mjs)';
const end = '  # quillstone:end';
const block = [begin, ...manifest.packages.map(({ name, file }) => `  '${name}': file:vendor/quillstone/${file}`), end].join('\n');
const text = readFileSync(workspaceFile, 'utf8');
const start = text.indexOf(begin);
const stop = text.indexOf(end);
let updated;
if (start >= 0 && stop > start) updated = `${text.slice(0, start)}${block}${text.slice(stop + end.length)}`;
else if (text.includes('\noverrides:\n')) updated = text.replace('\noverrides:\n', () => `\noverrides:\n${block}\n`);
else throw new Error('pnpm-workspace.yaml has no overrides section');
writeFileSync(workspaceFile, updated);
console.log(`pinned ${manifest.packages.length} packages at ${tag} (${manifest.gitSha.slice(0, 8)})`);
